package pertemuan2;

public class Increment {
    public static void main(String[] args) {
        int a = 7;
        
        System.out.println("Nilai Awal a    : " + a);
        System.out.println("\nPost-Increment (a++) : " + (a++));
        System.out.println("Nilai a : " + a);

        System.out.println("\nPre-Increment (++a) : " + (++a));
        System.out.println("Nilai a : " + a);
    }
}
